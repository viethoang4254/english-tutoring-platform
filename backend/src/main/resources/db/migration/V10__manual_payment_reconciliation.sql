-- Manual attestations are separate from authenticated provider transactions.
CREATE TABLE public.payment_reconciliation_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id BIGINT NOT NULL REFERENCES public.payments(id) ON DELETE RESTRICT,
 teacher_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
 bank_bin TEXT NOT NULL CHECK (bank_bin ~ '^[0-9]{6}$'),
 account_number TEXT NOT NULL CHECK (account_number ~ '^[0-9]{6,19}$'),
 bank_transaction_reference TEXT NOT NULL CHECK (length(bank_transaction_reference) BETWEEN 1 AND 128),
 received_at TIMESTAMPTZ NOT NULL,
 observed_amount NUMERIC(19,6) NOT NULL CHECK (observed_amount <> 'NaN'::numeric),
 currency TEXT NOT NULL CHECK (length(currency) BETWEEN 1 AND 8),
 transfer_description TEXT NOT NULL CHECK (length(transfer_description) BETWEEN 1 AND 1000),
 transfer_reference TEXT NOT NULL CHECK (length(transfer_reference) BETWEEN 1 AND 128),
 attested BOOLEAN NOT NULL,
 late BOOLEAN NOT NULL,
 attempted_at TIMESTAMPTZ NOT NULL,
 outcome TEXT NOT NULL CHECK (outcome IN ('SUCCESS','FAILED')),
 failure_reason TEXT,
 allocated BOOLEAN NOT NULL DEFAULT false,
 replay_of BIGINT REFERENCES public.payment_reconciliation_attempts(id) ON DELETE RESTRICT,
 CONSTRAINT ck_reconciliation_outcome CHECK (
   (outcome='FAILED' AND failure_reason IS NOT NULL AND NOT allocated AND replay_of IS NULL)
   OR (outcome='SUCCESS' AND failure_reason IS NULL AND attested AND currency='VND'
       AND observed_amount>0 AND received_at<=attempted_at
       AND ((allocated AND replay_of IS NULL) OR (NOT allocated AND replay_of IS NOT NULL))))
);
-- Account identity, not account-row identity: replacement submissions may use the same bank account.
CREATE UNIQUE INDEX uq_reconciliation_bank_allocation ON public.payment_reconciliation_attempts
 (bank_bin,account_number,bank_transaction_reference) WHERE allocated;
CREATE UNIQUE INDEX uq_reconciliation_payment_allocation ON public.payment_reconciliation_attempts
 (payment_id) WHERE allocated;
CREATE INDEX ix_reconciliation_history ON public.payment_reconciliation_attempts(payment_id,id DESC);
CREATE FUNCTION public.preserve_reconciliation_attempt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Reconciliation evidence is append-only' USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER preserve_reconciliation_attempt BEFORE UPDATE OR DELETE ON public.payment_reconciliation_attempts
 FOR EACH ROW EXECUTE FUNCTION public.preserve_reconciliation_attempt();
CREATE TRIGGER preserve_reconciliation_history BEFORE TRUNCATE ON public.payment_reconciliation_attempts
 FOR EACH STATEMENT EXECUTE FUNCTION public.preserve_reconciliation_attempt();
